func TestTitleFromToolWinsOverPrompt(t *testing.T) {
	index := NewIndex()
	index.Observe(capture.SessionEvent{
		SessionID: "s1", Kind: capture.KindMessage, TS: 1,
		PromptContext: "<caveat>generated by a local command</caveat> do the thing",
	})
	if got, _ := index.Get("s1"); got.Label() == "" || got.Label() == "(untitled)" {
		t.Fatalf("label = %q, want the prompt as a fallback", got.Label())
	}
	index.Observe(capture.SessionEvent{
		SessionID: "s1", Kind: capture.KindMessage, Raw: rawTitle("How demux works"),
	})
	got, _ := index.Get("s1")
	if got.Title != "How demux works" || got.Label() != "How demux works" {
		t.Fatalf("label = %q, want the tool's own title once it names the session", got.Label())
	}
	if got.LastActiveAt != 1 {
		t.Errorf("last active = %d; a rename carries no timestamp and is not activity", got.LastActiveAt)
	}
}

